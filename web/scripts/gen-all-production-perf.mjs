function panel(
    cfg,
    px,
    py,
    pw,
    ph,
    { title, yMax, yStep, yUnit, key, drawLegend },
) {
    const ax = px
    const ay = py
    const aw = pw
    const ah = ph
    const sx = (t) => ax + (t / X_MAX) * aw
    const sy = (v) => ay + ah - (v / yMax) * ah
    let b = ''
    b += `<text x="${(ax + aw / 2).toFixed(1)}" y="${(ay - 10).toFixed(1)}" text-anchor="middle" font-family="${FONT}" font-size="${cfg.panelTitleSize}" font-weight="700" fill="#838383">${esc(title)}</text>`
    b += `<rect x="${ax}" y="${ay}" width="${aw}" height="${ah}" fill="none" stroke="#83838355" stroke-width="1"/>`
    for (let v = 0; v <= yMax + 1e-9; v += yStep) {
        const yy = sy(v)
        b += `<line x1="${ax}" y1="${yy.toFixed(1)}" x2="${ax + aw}" y2="${yy.toFixed(1)}" stroke="#83838318" stroke-width="1"/>`
        b += `<text x="${(ax - 7).toFixed(1)}" y="${(yy + 4).toFixed(1)}" text-anchor="end" font-family="${FONT}" font-size="${cfg.tickSize}" fill="#838383">${v}${yUnit}</text>`
    }
    for (let t = 0; t <= X_MAX; t += 2000) {
        const xx = sx(t)
        b += `<line x1="${xx.toFixed(1)}" y1="${ay}" x2="${xx.toFixed(1)}" y2="${ay + ah}" stroke="#83838312" stroke-width="1"/>`
        b += `<text x="${xx.toFixed(1)}" y="${(ay + ah + 18).toFixed(1)}" text-anchor="middle" font-family="${FONT}" font-size="${cfg.tickSize}" fill="#838383">${t}</text>`
    }
    const clipId = `clip-${key}-${cfg.W}`
    b += `<clipPath id="${clipId}"><rect x="${ax}" y="${ay}" width="${aw}" height="${ah}"/></clipPath>`
    b += `<g clip-path="url(#${clipId})">`
    for (const s of SERIES) {
        const data = key === 'tps' ? s.tps : s.mfu
        if (!data) continue
        let d = ''
        data.forEach(([t, v], i) => {
            d += `${i ? 'L' : 'M'}${sx(t).toFixed(1)} ${sy(Math.min(v, yMax * 1.15)).toFixed(1)} `
        })
        const dashAttr = s.dash ? ` stroke-dasharray="${s.dash}"` : ''
        b += `<path d="${d.trim()}" fill="none" stroke="${s.color}" stroke-width="${cfg.lw}"${dashAttr} opacity="0.92"/>`
    }
    b += '</g>'
    b += `<text x="${(ax + aw / 2).toFixed(1)}" y="${(ay + ah + 40).toFixed(1)}" text-anchor="middle" font-family="${FONT}" font-size="${cfg.axisSize}" fill="#838383">tokens consumed (B)</text>`

    if (drawLegend) {
        // legend in the empty lower band of the TPS panel (20B chains sit ~350-450,
        // 2B ~2000-4700, so the mid band around 1200-1800 TPS on the right is clear).
        const lx = sx(4300)
        let ly = sy(1850)
        const rowH = cfg.legendSize + 6
        const order = [SERIES[4], SERIES[1], SERIES[0], SERIES[3], SERIES[2]]
        for (const s of order) {
            const dashAttr = s.dash ? ` stroke-dasharray="6 3"` : ''
            b += `<line x1="${lx}" y1="${(ly - 4).toFixed(1)}" x2="${lx + 22}" y2="${(ly - 4).toFixed(1)}" stroke="${s.color}" stroke-width="${cfg.lw + 0.4}"${dashAttr}/>`
            b += `<text x="${lx + 28}" y="${ly.toFixed(1)}" font-family="${FONT}" font-size="${cfg.legendSize}" font-weight="700" fill="${s.color}">${esc(s.label)}</text>`
            ly += rowH
        }
    }
    return b
}

function buildSVG(cfg) {
    const { W, H, M } = cfg
    let body = ''
    body += `<text x="${W / 2}" y="28" text-anchor="middle" font-family="${FONT}" font-size="${cfg.titleSize}" font-weight="700" fill="#838383">Throughput and MFU across every chain</text>`

    const mobile = cfg.panelGap === 0
    if (mobile) {
        const pw = W - M.left - M.right
        const ph = (H - M.top - M.bottom - 48) / 2
        body += panel(cfg, M.left, M.top, pw, ph, {
            title: 'Tokens / sec / GPU',
            yMax: TPS_MAX,
            yStep: 1000,
            yUnit: '',
            key: 'tps',
            drawLegend: true,
        })
        body += panel(cfg, M.left, M.top + ph + 60, pw, ph, {
            title: 'Model FLOPs Utilization (TT only)',
            yMax: MFU_MAX,
            yStep: 5,
            yUnit: '%',
            key: 'mfu',
            drawLegend: false,
        })
    } else {
        const pw = (W - M.left - M.right - cfg.panelGap) / 2
        const ph = H - M.top - M.bottom
        body += panel(cfg, M.left, M.top, pw, ph, {
            title: 'Tokens / sec / GPU',
            yMax: TPS_MAX,
            yStep: 1000,
            yUnit: '',
            key: 'tps',
            drawLegend: true,
        })
        body += panel(cfg, M.left + pw + cfg.panelGap, M.top, pw, ph, {
            title: 'Model FLOPs Utilization (TT only)',
            yMax: MFU_MAX,
            yStep: 5,
            yUnit: '%',
            key: 'mfu',
            drawLegend: false,
        })
    }

    return `<?xml version="1.0" encoding="utf-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" font-family="${FONT}">
${fontDefs()}
${body}
</svg>
`
}

