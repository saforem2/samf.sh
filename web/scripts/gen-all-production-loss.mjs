function buildSVG(cfg) {
    const { W, H, M } = cfg
    const ax = M.left
    const ay = M.top
    const aw = W - M.left - M.right
    const ah = H - M.top - M.bottom
    const sx = (t) => ax + (t / X_MAX) * aw
    const sy = (v) => ay + ah - ((v - Y_MIN) / (Y_MAX - Y_MIN)) * ah
    const clampY = (v) => Math.max(Y_MIN - 0.5, Math.min(Y_MAX + 0.5, v))

    let body = ''
    body += `<text x="${W / 2}" y="28" text-anchor="middle" font-family="${FONT}" font-size="${cfg.titleSize}" font-weight="700" fill="#838383">AuroraGPT production: every chain, one axis</text>`
    body += `<text x="${W / 2}" y="49" text-anchor="middle" font-family="${FONT}" font-size="${cfg.subSize}" fill="#838383">training loss vs tokens, all canonical pretraining runs overlaid</text>`

    // plot box + y grid/ticks
    body += `<rect x="${ax}" y="${ay}" width="${aw}" height="${ah}" fill="none" stroke="#83838355" stroke-width="1"/>`
    for (let v = 2.0; v <= 4.5 + 1e-9; v += 0.5) {
        const yy = sy(v)
        body += `<line x1="${ax}" y1="${yy.toFixed(1)}" x2="${ax + aw}" y2="${yy.toFixed(1)}" stroke="#83838318" stroke-width="1"/>`
        body += `<text x="${(ax - 8).toFixed(1)}" y="${(yy + 5).toFixed(1)}" text-anchor="end" font-family="${FONT}" font-size="${cfg.tickSize}" fill="#838383">${v.toFixed(1)}</text>`
    }
    // x grid/ticks (every 1000 B)
    for (let t = 0; t <= X_MAX; t += 1000) {
        const xx = sx(t)
        body += `<line x1="${xx.toFixed(1)}" y1="${ay}" x2="${xx.toFixed(1)}" y2="${ay + ah}" stroke="#83838312" stroke-width="1"/>`
        body += `<text x="${xx.toFixed(1)}" y="${(ay + ah + 20).toFixed(1)}" text-anchor="middle" font-family="${FONT}" font-size="${cfg.tickSize}" fill="#838383">${t}</text>`
    }

    // MDS stage boundaries (dotted verticals, labelled)
    for (const [tok, label] of STAGES) {
        if (tok > X_MAX) continue
        const xx = sx(tok)
        body += `<line x1="${xx.toFixed(1)}" y1="${ay}" x2="${xx.toFixed(1)}" y2="${ay + ah}" stroke="#83838399" stroke-width="1" stroke-dasharray="2 3"/>`
        body += `<text x="${(xx - 4).toFixed(1)}" y="${(ay + 12).toFixed(1)}" text-anchor="end" font-family="${FONT}" font-size="${cfg.stageSize}" fill="#777" transform="rotate(-90 ${(xx - 4).toFixed(1)} ${(ay + 12).toFixed(1)})">${esc(label)}</text>`
    }

    // curves (clipped to plot box)
    const clipId = `plot-${cfg.W}`
    body += `<clipPath id="${clipId}"><rect x="${ax}" y="${ay}" width="${aw}" height="${ah}"/></clipPath>`
    body += `<g clip-path="url(#${clipId})">`
    for (const s of SERIES) {
        let d = ''
        s.data.forEach(([t, v], i) => {
            d += `${i ? 'L' : 'M'}${sx(t).toFixed(1)} ${sy(clampY(v)).toFixed(1)} `
        })
        const dashAttr = s.dash ? ` stroke-dasharray="${s.dash}"` : ''
        body += `<path d="${d.trim()}" fill="none" stroke="${s.color}" stroke-width="${cfg.lw}"${dashAttr}/>`
    }
    body += '</g>'

    // axis labels
    body += `<text x="${(ax + aw / 2).toFixed(1)}" y="${(H - 14).toFixed(1)}" text-anchor="middle" font-family="${FONT}" font-size="${cfg.axisSize}" fill="#838383">tokens consumed (B)</text>`
    body += `<text x="18" y="${(ay + ah / 2).toFixed(1)}" text-anchor="middle" font-family="${FONT}" font-size="${cfg.axisSize}" fill="#838383" transform="rotate(-90 18 ${(ay + ah / 2).toFixed(1)})">loss</text>`

    // legend: parked in the empty upper-mid band (x ~4600-7900 B, loss > 3.0),
    // clear of every curve and the stage-boundary labels. Order: MDS ref first,
    // then 2B chains, then 20B chains. label + "end loss @ % of 4.67T target".
    const legOrder = [SERIES[4], SERIES[1], SERIES[0], SERIES[3], SERIES[2]]
    const lx = sx(4820)
    let ly = sy(4.18)
    const rowH = cfg.legendSize + 7
    for (const s of legOrder) {
        const dashAttr = s.dash ? ` stroke-dasharray="6 3"` : ''
        body += `<line x1="${lx}" y1="${(ly - 4).toFixed(1)}" x2="${lx + 24}" y2="${(ly - 4).toFixed(1)}" stroke="${s.color}" stroke-width="${cfg.lw + 0.4}"${dashAttr}/>`
        body += `<text x="${lx + 30}" y="${ly.toFixed(1)}" font-family="${FONT}" font-size="${cfg.legendSize}" fill="#666"><tspan font-weight="700" fill="${s.color}">${esc(s.label)}</tspan> <tspan fill="#8a8a8a">${esc(s.meta)}</tspan></text>`
        ly += rowH
    }

    return `<?xml version="1.0" encoding="utf-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" font-family="${FONT}">
${fontDefs()}
${body}
</svg>
`
}

